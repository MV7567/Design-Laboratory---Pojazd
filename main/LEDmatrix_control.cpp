//---------------- INTERNAL HELPER ----------------
static void showIcon(const uint8_t icon[8][12]){
  static uint8_t buffer[8*12];

  for(int r=0; r<8; r++){
    for(int c=0; c<12; c++){
      buffer[r*12 + c] = icon[r][c];
    }
  }
  
  matrix.clear();
  matrix.loadPixels(buffer, 8*12);
}

//---------------- FUNCTIONS ----------------
void setupLEDMatrix(){
  matrix.begin();
  showIcon(heart);
}

